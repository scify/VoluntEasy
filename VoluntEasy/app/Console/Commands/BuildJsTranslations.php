<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Write the translations to public/messages.js for the browser.
 *
 * The file defines the global "Lang" object: Lang.get('file.key', {name: 'x'}),
 * Lang.choice('file.key', count), Lang.has('file.key') and Lang.setLocale('el').
 * Run it again after a change in resources/lang.
 */
class BuildJsTranslations extends Command
{
    protected $signature = 'lang:js {--output=public/messages.js : The file to write}';

    protected $description = 'Write the translations to a JavaScript file for the browser';

    public function handle(): int
    {
        $messages = [];
        $langPath = $this->laravel->langPath();

        foreach (File::directories($langPath) as $localeDir) {
            $locale = basename($localeDir);
            foreach (File::allFiles($localeDir) as $file) {
                if ($file->getExtension() !== 'php') {
                    continue;
                }
                // "entities/volunteers" for resources/lang/el/entities/volunteers.php
                $group = str_replace(['\\', '.php'], ['/', ''], $file->getRelativePathname());
                $lines = require $file->getPathname();
                if (is_array($lines)) {
                    $messages["{$locale}.{$group}"] = $lines;
                }
            }
        }
        ksort($messages);

        $json = json_encode($messages, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
        $fallback = json_encode((string) config('app.fallback_locale'));

        $script = <<<JS
/* Generated by "php artisan lang:js". Do not edit. */
(function (root) {
    'use strict';
    var messages = {$json};
    var locale = document.documentElement.lang || {$fallback};
    var fallback = {$fallback};

    function find(key, loc) {
        var parts = key.split('.');
        var group = parts.shift();
        var value = messages[loc + '.' + group];
        while (value !== undefined && parts.length) {
            value = value === null ? undefined : value[parts.shift()];
        }
        return typeof value === 'string' ? value : undefined;
    }

    function replace(text, replacements) {
        Object.keys(replacements || {}).forEach(function (name) {
            text = text.split(':' + name).join(String(replacements[name]));
        });
        return text;
    }

    // Laravel pluralisation: "one|many", "{0} none|[1,19] some|[20,*] many"
    function choose(text, count) {
        var segments = text.split('|');
        for (var i = 0; i < segments.length; i++) {
            var m = segments[i].match(/^\s*(\{(\d+)\}|\[(\d+|\*),(\d+|\*)\])\s*([\s\S]*)$/);
            if (!m) continue;
            if (m[2] !== undefined && Number(m[2]) === count) return m[5];
            if (m[3] !== undefined) {
                var from = m[3] === '*' ? -Infinity : Number(m[3]);
                var to = m[4] === '*' ? Infinity : Number(m[4]);
                if (count >= from && count <= to) return m[5];
            }
        }
        if (segments.length === 1) return segments[0];
        return (count === 1 ? segments[0] : segments[1]).replace(/^\s*(\{\d+\}|\[[^\]]*\])\s*/, '');
    }

    root.Lang = {
        setLocale: function (value) { locale = value; },
        getLocale: function () { return locale; },
        has: function (key) { return find(key, locale) !== undefined; },
        get: function (key, replacements) {
            var text = find(key, locale);
            if (text === undefined) text = find(key, fallback);
            return text === undefined ? key : replace(text, replacements);
        },
        choice: function (key, count, replacements) {
            var text = this.get(key);
            if (text === key) return key;
            return replace(choose(text, Number(count)), Object.assign({count: count}, replacements || {}));
        }
    };
})(window);

JS;

        File::put(base_path((string) $this->option('output')), $script);
        $this->info('Wrote '.count($messages).' translation groups to '.$this->option('output'));

        return self::SUCCESS;
    }
}
